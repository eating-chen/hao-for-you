"""Tools exposed to the chat agent."""
from __future__ import annotations

from dataclasses import dataclass, replace
from datetime import date as Date
from datetime import datetime
from typing import Annotated
from zoneinfo import ZoneInfo

from langchain.tools import ToolRuntime, tool
from pydantic import Field

from app.service.google_calendar_service import (
    CalendarToolResult,
    GoogleCalendarGateway,
)
from app.service.calendar_date_resolver import resolve_calendar_date


TAIPEI_TIMEZONE = ZoneInfo("Asia/Taipei")


@dataclass(frozen=True)
class AgentContext:
    """Trusted request data injected by the application, not generated by the LLM."""

    user_id: str
    platform: str


@tool
async def create_google_calendar_event(
    title: Annotated[
        str,
        Field(description="行程標題，例如：打球、部門會議；不可自行增加使用者未提及的內容"),
    ],
    date: Annotated[
        str,
        Field(
            description=(
                "行程日期，格式 YYYY-MM-DD；使用者未指定年份時，"
                "依目前台北日期選擇下一個尚未過去的日期"
            )
        ),
    ],
    runtime: ToolRuntime[AgentContext],
    description: Annotated[
        str | None,
        Field(description="行程補充說明；使用者未提供時省略，不可自行編造"),
    ] = None,
    start_time: Annotated[
        str | None,
        Field(
            description=(
                "開始時間，24 小時制，格式 HH:MM:SS；"
                "非全天行程必填，全天行程省略"
            )
        ),
    ] = None,
    end_time: Annotated[
        str | None,
        Field(
            description=(
                "結束時間，24 小時制，格式 HH:MM:SS；"
                "必須晚於開始時間，使用者未提供時省略"
            )
        ),
    ] = None,
    all_day: Annotated[
        bool,
        Field(description="是否為全天行程；只有使用者明確表示全天時才設為 true"),
    ] = False,
) -> str:
    """使用者要求新增 Google Calendar 行程時使用；若未授權則回傳授權網址。"""
    if runtime.context.platform != "line":
        return CalendarToolResult(
            status="error",
            message="目前只有 LINE 使用者可以連結 Google Calendar。",
            error_code="UNSUPPORTED_PLATFORM",
        ).to_json()

    try:
        resolved_date = resolve_calendar_date(
            user_text=_latest_user_text(runtime.state),
            model_date=date,
            today=_today_in_taipei(),
        )
    except ValueError as exc:
        return CalendarToolResult(
            status="error",
            message=str(exc),
            error_code="INVALID_USER_DATE",
        ).to_json()

    result = await GoogleCalendarGateway().create_event(
        line_user_id=runtime.context.user_id,
        title=title,
        date=resolved_date,
        description=description,
        start_time=start_time,
        end_time=end_time,
        all_day=all_day,
    )
    return replace(result, resolved_date=resolved_date).to_json()


def _latest_user_text(state: object) -> str:
    if not isinstance(state, dict):
        return ""
    for message in reversed(state.get("messages", [])):
        if getattr(message, "type", None) != "human":
            continue
        content = getattr(message, "content", "")
        if isinstance(content, str):
            return content
        if isinstance(content, list):
            return "".join(
                str(block.get("text", "")) if isinstance(block, dict) else str(block)
                for block in content
            )
    return ""


def _today_in_taipei() -> Date:
    return datetime.now(tz=TAIPEI_TIMEZONE).date()


AGENT_TOOLS = [create_google_calendar_event]
